    private val hookCommands = listOf(
        "ls", "swift test", "git status", "cat README.md", "pwd", "rm -rf build", "echo hi", "(no command)", "",
        "ls " + "a".repeat(1195) + "…", "ls [redacted]", "ls \\\n-la", "git diff",
    )
    private val hookDescriptions = listOf(
        "", "# List", "# rm -rf /", "# a\n# b",
        "# List\n\n— recent activity —\n[Bash] ls\n" + "t".repeat(1500),
    )
    private val hookSeps = listOf("\n", "\r\n", "\n$ ", "\r\n$ ", "\n\n", "\r")
    private val hookPrefixes = listOf(
        "$ ", "$ \n", "$  ", "  $ ", "\n$ ", "$\t", "\uFF04 ", "# $ ", "#\n$ ", "\u2028$ ", "\u0085$ ",
    )

    @Test fun `no hook-style text is ever undoable, whatever the command, line endings or tail`() {
        val texts = arrayListOf(
            "$ ls\n$ ls\n$ ls", "$ ls\r\n$ pwd", "$ " + "ls; ".repeat(400), "[redacted", "$ [redacted]", "$ ls\u2029pwd",
        )
        for (p in hookPrefixes) for (c in hookCommands) for (d in hookDescriptions) for (sep in hookSeps) {
            texts.add(p + c + (if (d.isEmpty()) "" else sep + d))
        }
        assertEquals(4296, texts.size)
        val undoable = texts.filter { Reversibility.classify(it, rvCwd).level == Reversibility.UNDOABLE }
        assertEquals("hook text read as undoable: " + undoable.take(3), 0, undoable.size)
    }

    @Test fun `a hook page that claims a command is never undoable even with a clean description`() {
        assertNotEquals(Reversibility.UNDOABLE, Reversibility.classify("$ rm -rf build\n# Clean", rvCwd).level)
        assertNotEquals(Reversibility.UNDOABLE, Reversibility.classify("$ ls\n# rm -rf /", rvCwd).level)
    }
