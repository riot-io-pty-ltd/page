#!/bin/bash
# Compiles Tools/Shaders/NightWatch.metal into a metallib and embeds it, as
# base64, in Sources/ClaudePowerMode/UI/Components/NWShaderBlob.generated.swift.
#
# SwiftPM's `swift build` does not compile .metal files, and build.sh copies
# only the binary into Page.app, so the shaders ride inside the executable and
# load with ShaderLibrary(data:). Building the app needs no Metal toolchain;
# only this script does (install it once with
# `xcodebuild -downloadComponent MetalToolchain`). Run it after editing the
# .metal file and commit both.
set -euo pipefail
cd "$(dirname "$0")/../.."

SRC="Tools/Shaders/NightWatch.metal"
OUT="Sources/ClaudePowerMode/UI/Components/NWShaderBlob.generated.swift"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# macOS 14 is where SwiftUI's colorEffect / layerEffect begin.
xcrun -sdk macosx metal -c "$SRC" -o "$TMP/nw.air" -mmacosx-version-min=14.0 -Wall -Werror
xcrun -sdk macosx metallib "$TMP/nw.air" -o "$TMP/nw.metallib"

SUM="$(shasum -a 256 "$SRC" | cut -c1-16)"
{
    echo "// Generated by Tools/Shaders/build-shaders.sh from $SRC — do not edit."
    echo "// Source sha256 prefix: $SUM"
    echo ""
    echo "enum NWShaderBlob {"
    echo "    /// The compiled metallib, base64 (line breaks are ignored when decoding)."
    echo "    static let metallib = \"\"\""
    base64 -i "$TMP/nw.metallib" | fold -w 120
    echo "\"\"\""
    echo "    static let sourceDigest = \"$SUM\""
    echo "}"
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$TMP/nw.metallib" | tr -d ' ') bytes of metallib)"
