import Foundation

/// Installs the power helper — the narrow sudoers rule that lets Page run
/// `pmset disablesleep 0/1` (lid closed on battery) and `pmset schedule
/// [cancel] wake <stamp>` (wake before a scheduled resume) without a
/// password — from inside the app, behind the standard macOS admin prompt.
///
/// It writes exactly what `./install.sh --enable-power-helpers` writes
/// (`HelperInstallerTests` checks the two never drift), so either path can
/// be used and `--disable-power-helpers` removes both.
///
/// The fragment is embedded in the root script itself rather than staged in
/// a user-writable temp file, so nothing running as the user can swap its
/// contents between validation and install. As root it is written under a
/// dotted name (sudo ignores files in sudoers.d whose name contains a dot),
/// made root:wheel 0440, validated with `visudo -c -f`, moved into place,
/// and the whole sudoers config re-validated, rolling back on failure.
enum PowerHelperInstaller {
    enum Outcome: Equatable {
        case installed
        case cancelled
        case failed(String)
    }

    static let sudoersPath = "/etc/sudoers.d/claude-power-mode"
    static let visudo = "/usr/sbin/visudo"
    static let osascript = "/usr/bin/osascript"
    /// `ResumeScheduler.pmsetFormatter`'s "MM/dd/yyyy HH:mm:ss", digits only.
    /// Same text as install.sh's STAMP_PATTERN.
    static let stampPattern = #"[0-9][0-9]/[0-9][0-9]/[0-9][0-9][0-9][0-9] [0-9][0-9]\:[0-9][0-9]\:[0-9][0-9]"#
    /// The admin prompt can sit open while the user finds their password;
    /// ProcessRunner kills the child on timeout, so be generous.
    static let promptTimeout: TimeInterval = 600

    static let promptText = "Page needs your password once so it can keep agents running with the lid closed on battery. It will only ever be allowed to run pmset to turn that on and off and to schedule wakes."

    /// Letters, digits, dot, underscore, hyphen — nothing sudoers or the
    /// shell would treat specially.
    static func isValidUserName(_ name: String) -> Bool {
        !name.isEmpty && name.count <= 64 && name.unicodeScalars.allSatisfy {
            ("a"..."z").contains($0) || ("A"..."Z").contains($0) || ("0"..."9").contains($0)
                || $0 == "." || $0 == "_" || $0 == "-"
        } && !name.hasPrefix("-")
    }

    /// The rule lines, in install.sh's order.
    static func ruleLines(user: String) -> [String] {
        [
            "\(user) ALL=(root) NOPASSWD: /usr/bin/pmset schedule wake \(stampPattern)",
            "\(user) ALL=(root) NOPASSWD: /usr/bin/pmset schedule cancel wake \(stampPattern)",
            "\(user) ALL=(root) NOPASSWD: /usr/bin/pmset -a disablesleep 0",
            "\(user) ALL=(root) NOPASSWD: /usr/bin/pmset -a disablesleep 1",
        ]
    }

    static func fragment(user: String) -> String {
        let rules = ruleLines(user: user)
        return """
        # Generated by Page (Preferences > Power). Remove with
        # ./install.sh --disable-power-helpers.
        # Lets Page wake the Mac shortly before a Claude rate limit resets.
        \(rules[0])
        \(rules[1])
        # Lets Page keep agents running with the lid closed on battery (opt-in in
        # Preferences > Power). Exactly these two commands, no other arguments.
        \(rules[2])
        \(rules[3])

        """
    }

    /// The /bin/sh script run as root. Pure, for tests.
    static func rootScript(user: String) -> String {
        let dst = ProcessRunner.shellQuote(sudoersPath)
        let tmp = ProcessRunner.shellQuote(sudoersPath + ".page-tmp")
        return [
            "umask 077",
            "rm -f \(tmp)",
            "printf '%s' \(ProcessRunner.shellQuote(fragment(user: user))) > \(tmp) || exit 2",
            "/usr/sbin/chown root:wheel \(tmp) && /bin/chmod 0440 \(tmp) || { rm -f \(tmp); exit 2; }",
            "\(visudo) -c -q -f \(tmp) >/dev/null 2>&1 || { rm -f \(tmp); echo 'the rule failed validation' >&2; exit 3; }",
            "/bin/mv -f \(tmp) \(dst) || { rm -f \(tmp); exit 2; }",
            "\(visudo) -c -q >/dev/null 2>&1 || { rm -f \(dst); echo 'sudoers no longer validated; removed the rule' >&2; exit 4; }",
        ].joined(separator: "\n")
    }

    /// The AppleScript handed to osascript. Pure, for tests.
    static func appleScript(user: String) -> String {
        "do shell script \(ProcessRunner.appleScriptQuote(rootScript(user: user)))"
            + " with prompt \(ProcessRunner.appleScriptQuote(promptText))"
            + " with administrator privileges"
    }

    /// Pure: maps osascript's result to an outcome. -128 is "User canceled".
    static func outcome(_ r: ProcessRunner.Result) -> Outcome {
        if r.succeeded { return .installed }
        if r.stderr.contains("(-128)") { return .cancelled }
        if r.timedOut { return .failed("The password prompt timed out.") }
        if !r.launched { return .failed("Couldn’t run osascript.") }
        let detail = r.stderr.trimmingCharacters(in: .whitespacesAndNewlines)
        return .failed(detail.isEmpty ? "osascript exited with status \(r.status)." : detail)
    }

    /// Shows the admin prompt and installs the rule. Blocks until the user
    /// answers; never call on the main thread.
    static func install(user: String = NSUserName()) -> Outcome {
        guard isValidUserName(user) else {
            return .failed("Your account name (\(user)) has characters the rule can’t contain; use ./install.sh --enable-power-helpers instead.")
        }
        let r = ProcessRunner.run(osascript, ["-e", appleScript(user: user)], timeout: promptTimeout)
        let result = outcome(r)
        switch result {
        case .installed: Logger.shared.log("Power helper installed at \(sudoersPath)")
        case .cancelled: Logger.shared.log("Power helper install cancelled at the password prompt")
        case .failed(let why): Logger.shared.log("Power helper install failed: \(why)")
        }
        return result
    }
}
